export const CODE = OAUTHCAGE_ERROR_CODES;

export const OAUTHCAGE_SEVERITY = Object.freeze({
  INFO: 'info',
  WARNING: 'warning',
  ERROR: 'error',
  CRITICAL: 'critical'
});

function cleanDetail(detail) {
  if (typeof detail !== 'string' || detail.length === 0) return 'oauthcage security validation failed';
  return detail.length > 300 ? detail.slice(0, 300) : detail;
}

export class OAuthCageError extends Error {
  constructor(code, detail, options = {}) {
    super(cleanDetail(detail));
    this.name = 'OAuthCageError';
    this.code = typeof code === 'string' && code.startsWith('OAUTHCAGE_') ? code : CODE.INVALID_INPUT;
    this.detail = cleanDetail(detail);
    if (options && typeof options.field === 'string') this.field = options.field;
    if (options && options.cause !== undefined) this.cause = options.cause;
    Object.freeze(this);
  }

  toJSON() {
    const output = {
      name: this.name,
      code: this.code,
      detail: this.detail
    };
    if (this.field !== undefined) output.field = this.field;
    return output;
  }
}
